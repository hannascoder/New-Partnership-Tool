"""Case study report (HTML, printed to PDF by tools/print_pdf.js) for one country and topic of the disinformation monitor.

Usage: python pipeline/desinfo/case_study.py --country NP --topics Flood,"Natural disaster" --from 2026-08-15 --title "Nepal floods 2026" --out docs/case_study_nepal_floods.html
Everything comes from the data the monitor already has (site/data/desinfo/items.json, cache/un_items.json); nothing is invented.
Claim types are found by simple key words in the (translated) titles; the recommendations follow rules written below the data.
"""
import argparse
import collections
import datetime
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
D = ROOT / "site" / "data" / "desinfo"
E = html.escape

TYPES = [("AI-generated image or video", r"\bAI\b|artificial intelligence|\bIA\b|ai-generated|generated by|deepfake|inteligencia artificial"),
         ("Old or foreign footage shown as current", r"not from|isn't from|is not from|is from|not related|no connection|unrelated|old video|old photo|from 20\d\d|misrepresent|falsely (shared|linked|presented)|did not come|doesn't show|does not show|no es de|não é|n'est pas|pas de"),
         ("Fabricated claim about the cause or the events", r"fabricat|fake news|hoax|false claim|conspiracy|attack|cause|bulo")]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--country", required=True)
    ap.add_argument("--topics", required=True)
    ap.add_argument("--from", dest="since", default="2026-01-01")
    ap.add_argument("--title", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    items = json.load(open(D / "items.json", encoding="utf-8"))
    topics = {t["label"]: t["qid"] for t in json.load(open(D / "topics.json", encoding="utf-8"))["topics"]}
    cn = json.load(open(D / "countries.json", encoding="utf-8"))
    want = {topics[t.strip()] for t in a.topics.split(",") if t.strip() in topics}
    cname = cn[a.country]["name"].split(" (")[0]
    S = [i for i in items if i["date"] >= a.since and (a.country in i.get("about", []) or i["country"] == a.country) and want & set(i["topics"])]
    S.sort(key=lambda i: i["date"])
    if not S:
        raise SystemExit("no fact-checks match")
    en = lambda i: i.get("title_en") or i["title"]  # noqa: E731
    byday = collections.Counter(i["date"] for i in S)
    first, last, peak = S[0]["date"], S[-1]["date"], byday.most_common(1)[0]
    langs = collections.Counter(i["lang"][:2] for i in S)
    pubs = collections.Counter(i["publisher"] for i in S)
    rat = collections.Counter((i["rating"] or "").lower() for i in S if i["rating"])
    types = collections.defaultdict(list)
    for i in S:
        t = next((n for n, rx in TYPES if re.search(rx, en(i), re.I)), "Other")
        types[t].append(i)
    # UN material mentioning the country in the title
    un = [u for u in json.load(open(ROOT / "cache" / "un_items.json", encoding="utf-8")) if re.search(r"\b" + re.escape(cname) + r"\b", u["title"], re.I) and u["date"] >= a.since]
    un.sort(key=lambda u: u["date"])
    un_langs = collections.Counter(u["lang"] for u in un)

    # timeline (SVG bars per day)
    d0, d1 = datetime.date.fromisoformat(first), datetime.date.fromisoformat(last)
    days = [(d0 + datetime.timedelta(n)).isoformat() for n in range((d1 - d0).days + 1)]
    mx = max(byday.values())
    w = 760 / max(len(days), 1)
    bars = "".join(f'<rect x="{k * w:.1f}" y="{90 - 86 * byday.get(d, 0) / mx:.1f}" width="{max(w - 1, 1):.1f}" height="{86 * byday.get(d, 0) / mx:.1f}" fill="#009EDB"><title>{d}: {byday.get(d, 0)}</title></rect>' for k, d in enumerate(days))
    un_marks = "".join(f'<line x1="{days.index(u["date"]) * w + w / 2:.1f}" x2="{days.index(u["date"]) * w + w / 2:.1f}" y1="0" y2="92" stroke="#B45309" stroke-width="1" stroke-dasharray="3 2"/>' for u in un if u["date"] in days)

    rows = lambda lst: "".join(f'<tr><td>{u["date"]}</td><td>{E(u["agency"])}</td><td>{u["lang"]}</td><td><a href="{E(u["url"])}">{E(u["title"])}</a></td></tr>' for u in lst)  # noqa: E731
    ex = ""
    for t, lst in sorted(types.items(), key=lambda kv: (kv[0] == "Other", -len(kv[1]))):     # "Other" last
        ex += f"<h3>{E(t)} ({len(lst)})</h3><ul>" + "".join(f'<li>{i["date"]} · {E(i["publisher"])}: <a href="{E(i["url"])}">{E(en(i))}</a></li>' for i in lst[:5]) + "</ul>"
    first_un = un[0]["date"] if un else None
    recs = []
    if types.get("AI-generated image or video"):
        recs.append(f"<b>AI-generated media appeared during the crisis</b> ({len(types['AI-generated image or video'])} fact-checks). Prepare a short guide on how to recognise AI images and videos, ready to publish in the first 48 hours of a disaster.")
    if types.get("Old or foreign footage shown as current"):
        recs.append(f"<b>Old or foreign footage was passed off as current</b> ({len(types['Old or foreign footage shown as current'])} fact-checks). A standing reminder to check the source and date before sharing, plus a verified photo and video stream from the field (UN Verified), would help.")
    top = [l for l, _ in langs.most_common(3)]
    missing = [l for l in top if un_langs.get(l, 0) == 0]
    if missing:
        recs.append(f"<b>Language gap:</b> fact-checks appeared in {', '.join(top)}, but the UN articles found on this crisis were in {', '.join(f'{l} ({n})' for l, n in un_langs.most_common()) or 'none'}. No UN article in: {', '.join(missing)}.")
    recs.append("<b>None of the UN article titles found points to a circulating claim:</b> they describe the situation and the response (only the titles were read). A one-page \"what is not true\" fact sheet, updated daily while fact-checks keep coming, would fill that gap." if un else "<b>No UN article on this country was found in the archive.</b>")
    recs.append(f"<b>Timing:</b> fact-checks started on {first} and peaked on {peak[0]} ({peak[1]} in one day); the weeks around the peak are the window in which a prepared response matters most.")

    page = f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><title>{E(a.title)}</title><style>
    @page {{ size: A4; margin: 14mm; }} body {{ font: 10.5pt/1.45 'Noto Sans', 'Segoe UI', Arial, sans-serif; color:#0F1A2B; }}
    h1 {{ font-size: 21pt; color:#003D6B; margin: 4px 0 2px; }} h2 {{ font-size: 13pt; color:#003D6B; border-bottom: 2px solid #009EDB; padding-bottom: 2px; margin-top: 18px; }}
    h3 {{ font-size: 10.5pt; margin: 10px 0 2px; }} .sub {{ color:#5C6B7E; font-size: 9pt; }} .un {{ color:#5C6B7E; font-size:9pt; text-transform:uppercase; letter-spacing:.4px; }}
    .kpi {{ display:flex; gap:10px; margin:10px 0; }} .kpi div {{ border:1px solid #E3EBF1; border-radius:8px; padding:6px 12px; min-width:105px; }} .kpi b {{ font-size:18pt; display:block; color:#003D6B; }}
    table {{ border-collapse: collapse; width:100%; font-size:9pt; }} td, th {{ border-bottom:1px solid #E3EBF1; padding:3px 6px; text-align:left; vertical-align:top; }} th {{ background:#003D6B; color:#fff; }}
    a {{ color:#0072BC; }} ul {{ margin:2px 0 6px 18px; padding:0; }} li {{ margin:2px 0; }} .note {{ font-size:8.5pt; color:#5C6B7E; margin-top:14px; }}
    </style></head><body>
    <div class="un">United Nations · DGC Partnerships · Disinformation monitor</div><h1>{E(a.title)}</h1>
    <div class="sub">Scope: fact-checks about {E(cname)} (country of the fact-checker or named in the text) on {E(a.topics)} since {a.since}. Case study from the monitor's data · data as of {max(i['date'] for i in items)} · {len(S)} fact-checks by independent fact-checkers</div>
    <div class="kpi"><div><b>{len(S)}</b>fact-checks</div><div><b>{len(pubs)}</b>fact-checkers</div><div><b>{peak[1]}</b>on the peak day<br>({peak[0]})</div><div><b>{len(un)}</b>UN articles<br>on {E(cname)}</div></div>
    <h2>Timeline</h2><svg width="760" height="104" viewBox="0 0 760 104">{bars}{un_marks}</svg>
    <div class="sub">Fact-checks per day, {first} to {last}. Dashed lines = UN articles that name {E(cname)} in their title.</div>
    <h2>Key findings</h2><ul><li><b>Languages:</b> {', '.join(f'{l} {n}' for l, n in langs.most_common(5))}.</li>
    <li><b>Fact-checkers:</b> {', '.join(f'{E(p)} ({n})' for p, n in pubs.most_common(6))}.</li>
    <li><b>Ratings:</b> {', '.join(f'{E(r)} {n}' for r, n in rat.most_common(5))}.</li></ul>
    <h2>What was spread</h2>{ex}
    <h2>UN material on {E(cname)} in the same period</h2>{('<table><tr><th>Date</th><th>Source</th><th>Lang.</th><th>Title (link)</th></tr>' + rows(un) + '</table>') if un else '<p>None found in the archive.</p>'}
    <h2>Recommendations (rule based, for discussion)</h2><ul>{''.join(f'<li>{r}</li>' for r in recs)}</ul>
    <div class="note">Automatic evaluation of fact-checks published by independent fact-checkers; claim types are found by key words in the (machine-translated) titles and are only a guide. Topics and countries are assigned by rules. UN articles are those found in the public UN News and agency feeds that name the country in the title; articles that do not name it are not counted. Please check the originals before using any of this.</div>
    </body></html>"""
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(page, encoding="utf-8")
    print(f"{len(S)} fact-checks, first {first}, peak {peak}, UN articles {len(un)} -> {out}")


if __name__ == "__main__":
    main()
